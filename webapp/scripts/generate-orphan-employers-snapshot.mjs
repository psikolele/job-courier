// Aggiorna api/_orphan-employers-snapshot.js con i datori i cui annunci non sono agganciati
// alla loro anagrafica Arca24. Eseguito prima di vite build.
//
// The scan itself is in api/_orphan-employers.js: read its header for why these employers
// are invisible to the `company/jobs` probe and why the only way to find them is to open
// the anonymous ads. That module tolerates individual failures on purpose and reports
// counters instead; deciding whether the run is trustworthy is this script's job, because
// this is where the result gets committed to the repo. The verdict itself lives in
// _assess-orphan-scan.mjs, which is pure and tested — this file is only the plumbing.
//
// Any rejection leaves the committed `names`/`generatedAt` alone and the build carries on:
// a slightly stale list of employers is worth something, a truncated one is worth less than
// nothing. The one field a rejection CAN still change is `consecutiveCleanZero`, which has
// to move even on a rejected run so a clean-zero streak survives — or resets — across the
// fresh checkout every build starts from. See CLEAN_ZERO_THRESHOLD in _assess-orphan-scan.mjs.
import { writeFileSync } from 'node:fs';
import { collectOrphanEmployerNames } from '../api/_orphan-employers.js';
import {
  generatedAt as committedGeneratedAt,
  names as committedNames,
  consecutiveCleanZero as committedConsecutiveCleanZero,
} from '../api/_orphan-employers-snapshot.js';
import { assessScan, countRemoved, CLEAN_ZERO_THRESHOLD } from './_assess-orphan-scan.mjs';

const OUT = new URL('../api/_orphan-employers-snapshot.js', import.meta.url);

/**
 * Renders the committed snapshot module. Shared by both the accepted-run write and the
 * counter-only write below so the two can never drift into different file shapes.
 */
function renderSnapshot({ generatedAt, names, consecutiveCleanZero }) {
  return `// Generated by scripts/generate-orphan-employers-snapshot.mjs — do not edit by hand.
//
// Employers with at least one ad online that is not attached to their own Arca24 record.
// Names normalized with normalizeCompanyNameRaw, which KEEPS the legal form ("finders sa",
// not "finders"). That is deliberate: the stripped key alone cannot tell "Finders SA" (an
// employer absent from the roster) from "Finders Sagl" (a different entity that is on it
// and is not hiring), and matching across the two would advertise the wrong company.
// Read by api/_arca24.js to mark as hiring the companies the \`company/jobs\` probe cannot
// see. See api/_orphan-employers.js.
export const generatedAt = '${generatedAt}';
export const names = ${JSON.stringify(names, null, 2)};

// How many consecutive clean-zero runs (see _assess-orphan-scan.mjs) have found no orphan
// employers in a row, without yet reaching CLEAN_ZERO_THRESHOLD. Persisted here — not just
// in the build's own memory — because each Vercel build is a fresh checkout of this file;
// without it the streak could never survive from one build to the next. Stays 0 whenever
// \`names\` reflects an accepted run, clean-zero or not: it only holds a nonzero value while
// a clean-zero streak is still short of being trusted.
export const consecutiveCleanZero = ${consecutiveCleanZero};
`;
}

// Same shape as generate-companies-snapshot.mjs. The `.unref()` matters: without it the
// pending timer keeps the process alive for the whole budget after the work is done.
const withTimeout = (promise, ms) => Promise.race([
  promise,
  new Promise((_, reject) => {
    setTimeout(() => reject(new Error(`nessuna risposta in ${ms}ms`)), ms).unref();
  }),
]);

// Four minutes. The two live runs on 20.08.2026 each finished in about a minute and a half,
// so this is more than double a healthy run — wide enough that a merely slow portal still
// produces a usable snapshot. The ceiling exists for the other case: 120 listing pages at
// two attempts plus 150 detail pages, all crawling at the 6s request timeout, is roughly
// six and a half minutes added to every build, and that happens exactly when the portal is
// sick, i.e. when the run was going to be rejected anyway. Higher than the sibling's 120s
// because this scan is an order of magnitude more requests.
const BUDGET_MS = 240_000;

// Declared outside the try because the error branch must be able to print the counters.
let scan = null;

try {
  scan = await withTimeout(collectOrphanEmployerNames(), BUDGET_MS);

  const verdict = assessScan(scan, committedNames, committedConsecutiveCleanZero);

  if (verdict.reason === null) {
    // Alphabetical purely so the committed diff stays readable: this file is rewritten on
    // every build, and in scan order (newest ad first) a single new employer inserts at the
    // top and shifts every line. No consumer depends on the order — the lookup is by name.
    // Same comparison as the company sorts in _arca24.js so the two orderings agree.
    const names = [...scan.names].sort((a, b) => a.localeCompare(b, 'it', { sensitivity: 'base' }));

    writeFileSync(OUT, renderSnapshot({
      generatedAt: new Date().toISOString(),
      names,
      consecutiveCleanZero: verdict.consecutiveCleanZero,
    }));

    // The delta, not just the count: a healthy run has to leave a baseline in the build log,
    // or the counters printed on a future rejection have nothing to be compared against.
    const previous = new Set(committedNames);
    const added = names.filter((n) => !previous.has(n)).length;
    const removed = countRemoved(committedNames, names);
    console.log(`orphan employers snapshot: ${names.length} datori (+${added} / -${removed})`);
    console.log(`  contatori: ${counters(scan)}`);
  } else {
    // Rejected or still pending: `names`/`generatedAt` stay exactly as committed — a
    // slightly stale list of employers is worth something, a truncated or unproven one is
    // worth less than nothing. But the clean-zero streak still has to survive to the next
    // build, so if it changed (incremented toward the threshold, or reset off of an
    // in-progress streak by this non-qualifying run) the file is rewritten for that field
    // alone. Skipped when it didn't change, so a run that was never in a streak — the
    // common case — doesn't touch the file at all.
    if (verdict.consecutiveCleanZero !== committedConsecutiveCleanZero) {
      writeFileSync(OUT, renderSnapshot({
        generatedAt: committedGeneratedAt,
        names: committedNames,
        consecutiveCleanZero: verdict.consecutiveCleanZero,
      }));
    }

    if (verdict.pending) {
      // Distinct token from `[SNAPSHOT-REJECTED]` on purpose: this is not a suspected
      // broken scan, it is real evidence still short of CLEAN_ZERO_THRESHOLD. Searching a
      // build log for one token must not surface the other.
      console.warn(`[SNAPSHOT-PENDING] orphan employers snapshot: clean zero ${verdict.consecutiveCleanZero}/${CLEAN_ZERO_THRESHOLD} consecutive — not yet accepted (${verdict.reason}).`);
    } else {
      // `[SNAPSHOT-REJECTED]` is a stable token on purpose: a build log is searched by
      // someone who does not know this script exists, let alone the Italian wording of its
      // messages.
      console.warn(`[SNAPSHOT-REJECTED] orphan employers snapshot: non aggiornato (${verdict.reason}) — resta quello committato.`);
    }
    // And print the counters, not just the message. A file that did not get updated is
    // invisible in a build log, and the numbers that caused the rejection are exactly what
    // someone will need six weeks from now.
    console.warn(`  contatori: ${counters(scan)}`);
  }
} catch (error) {
  console.warn(`[SNAPSHOT-REJECTED] orphan employers snapshot: non aggiornato (${error.message}) — resta quello committato.`);
  if (scan) console.warn(`  contatori: ${counters(scan)}`);
}

// `withTimeout` is a race: when the budget wins, the scan keeps running, and its pending
// sockets keep the event loop alive. Without this the build would still wait out the full
// ~6.5 minute worst case, having printed the rejection at minute four and then gone silent
// — which reads as a hung build rather than a handled one, and is worse to diagnose than
// no budget at all. The exit is what makes BUDGET_MS an actual ceiling.
//
// Through the write callback rather than bare `process.exit(0)`: stdout to a pipe is async
// on Windows, and exiting straight after a `console.log` can truncate it — losing exactly
// the diagnostic lines above.
process.stdout.write('', () => process.exit(0));

/** The counters without the names array, which is noise near the detail cap. */
function counters({ names, pagesRequested, pagesFailed, detailsRequested, detailsFailed, truncated }) {
  return JSON.stringify({
    found: names.length, pagesRequested, pagesFailed, detailsRequested, detailsFailed, truncated,
  });
}
