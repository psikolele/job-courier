// Aggiorna api/_companies-snapshot.js con il roster delle aziende che assumono.
// Eseguito prima di vite build.
//
// `/api/companies?withJobs=1` walks the portal index and then reads one profile page per
// employer. Warm that costs ~2s; on a cold instance it has been measured at 56s and 93s,
// and the home showcase waits on it before it can paint anything at all. Nobody should sit
// through that: a snapshot committed to the repo gives a cold function something real to
// answer with on the spot while the live read finishes behind it.
//
// The roster is read from production rather than scraped again here. Doing the walk from a
// build machine took over 150s and still came back with half the employers unprobed, while
// production answers the same question from its edge cache in a fifth of a second — same
// data, already paid for.
//
// Two things keep that from feeding on itself. `X-Roster-Source` must say `live`, so a
// stand-in answer (which is a *previous* snapshot) is never written back as the new one —
// otherwise one stale roster would seed the next build's, and the next, with nothing ever
// correcting it. And any failure leaves the committed file alone: a stale roster is worth
// something, an empty one is worth nothing.
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://www.jobcourier.ch/api/companies?withJobs=1';
const OUT = new URL('../api/_companies-snapshot.js', import.meta.url);
const BUDGET_MS = 20_000;

// The budget has to cover reading the body, not just getting the headers back: production
// can start answering and then stream slowly, and an abort cleared at the headers leaves
// the build hanging on the rest with no deadline at all.
const ctrl = new AbortController();
const timer = setTimeout(() => ctrl.abort(), BUDGET_MS);

try {
  // Without a User-Agent the request comes back 403 — verified 10.08.2026.
  const response = await fetch(SOURCE, {
    signal: ctrl.signal,
    headers: { 'User-Agent': 'jobcourier-build/1.0', Accept: 'application/json' },
  });

  if (!response.ok) throw new Error(`HTTP ${response.status}`);

  const source = response.headers.get('x-roster-source');
  if (source !== 'live') throw new Error(`sorgente "${source || 'sconosciuta'}", non un roster vero`);

  const list = await response.json();
  if (!Array.isArray(list)) throw new Error('risposta non è una lista');

  const hiring = list.filter((c) => c.has_jobs === true);
  // Nobody hiring means the run was degraded, not that Ticino stopped recruiting: the
  // probe reports `null` when it fails, and every `null` is filtered out just above.
  if (hiring.length === 0) throw new Error('nessuna azienda risulta assumere');

  const body = `// Generated by scripts/generate-companies-snapshot.mjs — do not edit by hand.
//
// The roster of employers with at least one open position, as of the last build. Read by
// api/companies.js as the answer of last resort while a cold instance computes the real
// one. See that file for why it is allowed to be a little out of date.
export const generatedAt = '${new Date().toISOString()}';
export const companies = ${JSON.stringify(hiring, null, 2)};
`;
  writeFileSync(OUT, body);
  console.log(`companies snapshot: ${hiring.length} aziende che assumono`);
} catch (error) {
  const reason = error.name === 'AbortError' ? `nessuna risposta in ${BUDGET_MS}ms` : error.message;
  console.warn(`companies snapshot: non aggiornato (${reason}) — resta quello committato.`);
} finally {
  clearTimeout(timer);
}
