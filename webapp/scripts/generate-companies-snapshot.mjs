// Aggiorna api/_companies-snapshot.js con il roster delle aziende che assumono.
// Eseguito prima di vite build.
//
// `/api/companies?withJobs=1` walks the portal index and then reads one profile page per
// employer. Warm that costs ~2s; on a cold instance it has been measured at 56s and 93s,
// and the home showcase waits on it before it can paint anything at all. Nobody should sit
// through that: a snapshot committed to the repo gives a cold function something real to
// answer with on the spot while the live read finishes behind it.
//
// The roster is computed here, from the portal, and not read back from production. Reading
// production looked cheaper — its edge cache answers in a fifth of a second — but it cannot
// work: the live read takes longer than the 4s budget `api/companies` gives it, so what
// production hands back is its own stand-in, which is a previous snapshot. Feeding that
// back in would leave the snapshot copying itself with nothing ever correcting it.
//
// The walk here used to be the impossible one, at over 150s with half the employers still
// unprobed. That was the profile page, which no longer lists ads; against `company/jobs` a
// full run is ~35s, which a build can afford.
//
// Any failure leaves the committed file alone: a stale roster is worth something, an empty
// one is worth nothing.
// ORDER DEPENDENCY, do not reorder in package.json: this must run AFTER
// generate-orphan-employers-snapshot.mjs. `fetchCompanies` reads
// api/_orphan-employers-snapshot.js to know which employers publish ads that are not
// linked to their profile, and that file is only refreshed by the orphan generator.
//
// Vercel rewrites the snapshot inside the build sandbox and never commits it back, so the
// copy in git never ages forward. Run this first and, from the eighth day after the last
// human-committed build, it reads an EXPIRED snapshot: the roster it writes — and the
// static hub page prerendered from it — silently lose the orphan employers, while the
// runtime lambda, which by then has the freshly regenerated file, still shows them. The
// two disagree and nothing fails.
import { writeFileSync } from 'node:fs';
import { fetchCompanies } from '../api/_arca24.js';

const OUT = new URL('../api/_companies-snapshot.js', import.meta.url);
const BUDGET_MS = 120_000;

// `unref` so the pending timer never holds the build open once the walk has won the race.
const withTimeout = (promise, ms) => Promise.race([
  promise,
  new Promise((_, reject) => {
    setTimeout(() => reject(new Error(`nessuna risposta in ${ms}ms`)), ms).unref();
  }),
]);

try {
  const list = await withTimeout(fetchCompanies({ withJobStatus: true, verifyLogos: true }), BUDGET_MS);

  const hiring = list.filter((c) => c.has_jobs === true);
  // The same floor `api/companies.js` applies, for the same reason: a run that answers
  // with only the handful the job feed names is a degraded run, not a quiet job market,
  // and writing it here would bake that into every build until the next one.
  const MIN_HEALTHY_HIRING = 8;
  const MIN_HEALTHY_ROSTER = 12;
  if (hiring.length < MIN_HEALTHY_HIRING && list.length < MIN_HEALTHY_ROSTER) {
    throw new Error(`roster di ${list.length} aziende, ${hiring.length} assumono: sotto entrambe le soglie (${MIN_HEALTHY_ROSTER}/${MIN_HEALTHY_HIRING})`);
  }

  const body = `// Generated by scripts/generate-companies-snapshot.mjs — do not edit by hand.
//
// The roster of employers with at least one open position, as of the last build. Read by
// api/companies.js as the answer of last resort while a cold instance computes the real
// one. See that file for why it is allowed to be a little out of date.
export const generatedAt = '${new Date().toISOString()}';
export const companies = ${JSON.stringify(hiring, null, 2)};
`;
  writeFileSync(OUT, body);
  console.log(`companies snapshot: ${hiring.length} aziende che assumono`);
} catch (error) {
  console.warn(`companies snapshot: non aggiornato (${error.message}) — resta quello committato.`);
}
