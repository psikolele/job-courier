// Aggiorna api/_jobs-snapshot.js con l'elenco delle offerte pubblicate sul feed.
// Eseguito prima di vite build, subito dopo generate-companies-snapshot.mjs.
//
// `/offerte` used to be a static shell: no <h1>, no meta description, and — the part that
// actually mattered to Ahrefs — zero <a href> to any job ad. The 236 ads on the site exist
// only in api/sitemap-jobs.xml, which a crawler reads as a list of URLs with nothing
// linking to them: "orphan page (no incoming internal links)" for every single one. A
// build-time snapshot gives scripts/prerender-canonicals.mjs something to render real
// <a href="/offerta/:id"> links from, the same way the companies snapshot feeds the
// aziende-che-assumono hub.
//
// Only fields actually read off the feed go in here — id, title, company name, location,
// sector, role — mirroring api/sitemap-jobs.xml.js's own collection rather than
// re-implementing scraping or HTML parsing: this reuses fetchJobs() from api/_arca24.js
// directly.
//
// Feed-resilience rules (00_Wiki/job-courier/jobroom-feed-resilience.md), same as the
// companies snapshot: never `find(...) || list[0]`, no placeholder values, and any run
// that comes back thin fails loudly and leaves the committed file untouched rather than
// baking a degraded list into the next deploy.
import { writeFileSync } from 'node:fs';
import { isArca24Enabled, fetchJobs } from '../api/_arca24.js';

const OUT = new URL('../api/_jobs-snapshot.js', import.meta.url);
const BUDGET_MS = 120_000;

// Same floor as api/jobs.js's MIN_HEALTHY_JOBS / api/sitemap-jobs.xml.js's own gate: a
// run that returns only a handful of ads is a degraded read, not a quiet job market.
const MIN_HEALTHY_JOBS = 10;

// How deep the nightly walk goes.
//
// Not an ordering: measured 09/09/2026, `published_at` is the same day on essentially
// every ad in the catalogue — 881 of 900 across sixty pages, and page 442 of 442 reads
// the same date as page 1. Upstream reimports the whole catalogue daily and rewrites the
// date with it, so there is no chronology in this source to sort by and "the latest ads"
// cannot be recovered from it. (The RSS feed does carry a real `insert-date`; getting at
// it needs a stable URL from Arca24 — see 00_Wiki/job-courier/.)
//
// What depth does buy is coverage, which is what the snapshot is for: it feeds
// prerender-canonicals, and every ad missing from it is an ad no page links to. 300 ads
// was 4.5% of the catalogue; 900 is 13%, and takes the employers represented from 9 to
// 16. Measured cost at concurrency 10: ~5s wall, ~3s CPU — paid once a night by the
// build, never by a visitor.
const MAX_JOBS = 900;
const PAGES = Math.ceil(MAX_JOBS / 15);

// Sixty requests at once against a partner portal is how bot protection gets tripped,
// and that would take api/companies down with it, not just this script.
const CONCURRENCY = 10;

// `unref` so the pending timer never holds the build open once the fetch has won the race.
const withTimeout = (promise, ms) => Promise.race([
  promise,
  new Promise((_, reject) => {
    setTimeout(() => reject(new Error(`nessuna risposta in ${ms}ms`)), ms).unref();
  }),
]);

try {
  const arca24 = await isArca24Enabled();
  if (!arca24) throw new Error('feed Arca24 non attivo — nessuna primitiva jobroom da riusare qui');

  const jobs = await withTimeout(
    fetchJobs({ pages: PAGES, maxJobs: MAX_JOBS, concurrency: CONCURRENCY }),
    BUDGET_MS,
  );

  const withId = jobs.filter((j) => j.jobroom_id);
  if (withId.length < MIN_HEALTHY_JOBS) {
    throw new Error(`solo ${withId.length} offerte con id valido, sotto la soglia di ${MIN_HEALTHY_JOBS}`);
  }

  const snapshot = withId.map((j) => ({
    id: j.jobroom_id,
    title: j.title,
    company: j.company?.name || 'Azienda Riservata',
    location: j.location,
    sector: j.sector,
    role: j.role,
  }));

  const body = `// Generated by scripts/generate-jobs-snapshot.mjs — do not edit by hand.
//
// Offerte pubblicate sul feed, come risultavano all'ultimo build. Letto da
// scripts/prerender-canonicals.mjs per dare a /offerte una lista reale di
// <a href="/offerta/:id"> — vedi quel file per il perché.
export const generatedAt = '${new Date().toISOString()}';
export const jobs = ${JSON.stringify(snapshot, null, 2)};
`;
  writeFileSync(OUT, body);
  console.log(`jobs snapshot: ${snapshot.length} offerte`);
} catch (error) {
  console.warn(`jobs snapshot: non aggiornato (${error.message}) — resta quello committato.`);
}
